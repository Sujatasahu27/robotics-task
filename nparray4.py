import numpy as np

a = np.array([1, 2, 3])
b = np.array([4, 5, 6])

# Perform operations:
addition = a + b
subtraction = a - b
multiplication = a * b
division = a / b
power_of_3 = a ** 3
square = a ** 2
mean_a = np.mean(a)  # Mean of array 'a'

print("Addition:", addition)
print("Subtraction:", subtraction)
print("Multiplication:", multiplication)
print("Division:", division)
print("Power of 3 (a):", power_of_3)
print("Square (a):", square)
print("Mean of a:", mean_a)